import { promises as fs } from 'fs';
import { join, normalize } from 'path';

import { parseProtocol } from 'vuesp-struct';

const check = process.argv.includes('--check');

const cwd = process.cwd();
const pathProtocol = normalize(join(cwd, '../src/const/protocol.h'));
const pathJson = normalize(join(cwd, 'json'));
const pathDefaultJson = normalize(join(cwd, 'public/default.json'));
const pathTs = normalize(join(cwd, 'src/generated/protocol.ts'));
const pathHeader = normalize(join(cwd, '../src/const/protocol.generated.h'));

const mergeJsonFiles = async (path) => {
  const items = await fs.readdir(path);
  const result = {};

  for (const item of items) {
    const itemPath = join(path, item);
    const stat = await fs.stat(itemPath);

    if (stat.isDirectory()) {
      result[item] = await mergeJsonFiles(itemPath);
    } else if (stat.isFile() && item.endsWith('.json')) {
      const fileContent = await fs.readFile(itemPath, 'utf8');
      result[item.replace('.json', '')] = JSON.parse(fileContent);
    }
  }

  return result;
};

const valueType = (field) => {
  if (field.name === 'command' && field.kind === 'scalar' && field.type === 'uint8_t') return 'TCommand';

  if (field.type === 'char' && field.kind === 'scalar') return 'string';
  if (field.kind === 'struct') {
    const base = `I${field.type}`;
    return (field.dimensions ?? []).reduce((acc) => `${acc}[]`, base);
  }

  const base = field.type === 'bool' ? 'boolean' : 'number';
  return (field.dimensions ?? []).reduce((acc) => `${acc}[]`, base);
};

const renderEnums = (enums) =>
  Object.entries(enums)
    .map(([name, values]) => {
      const entries = Object.entries(values)
        .map(([key, value]) => `${key}: ${value}`)
        .join(', ');
      return `  ${name}: { ${entries} },`;
    })
    .join('\n');

const renderStructs = (structs) =>
  Object.entries(structs)
    .map(([name, def]) => {
      const fields = def.fields
        .map((field) => {
          const dimensions = field.dimensions ? `, dimensions: [${field.dimensions.join(', ')}]` : '';
          return `    { name: '${field.name}', type: '${field.type}'${dimensions} },`;
        })
        .join('\n');
      return `  ${name}: [\n${fields}\n  ],`;
    })
    .join('\n');

const renderMessages = (protocol) => {
  const structNames = Object.keys(protocol.structs);
  const pairs = Object.keys(protocol.enums.KEY)
    .map((key) => {
      const struct = structNames.find((name) => name.toLowerCase() === key.toLowerCase());
      return struct ? [key, struct] : null;
    })
    .filter(Boolean);

  return `export interface IMessageMap {
${pairs.map(([key, struct]) => `  ${key}: I${struct};`).join('\n')}
}

export type TMessage =
${pairs.map(([key, struct]) => `  | { key: typeof KEY.${key}; object: I${struct} }`).join('\n')};`;
};

const renderInterfaces = (structs) =>
  Object.entries(structs)
    .map(([name, struct]) => {
      const fields = struct.fields
        .map((field) => `  ${field.name}${field.name === 'key' ? '?' : ''}: ${valueType(field)};`)
        .join('\n');
      return `export interface I${name} {\n${fields}\n}`;
    })
    .join('\n\n');

const renderTs = (protocol) => `// AUTO-GENERATED by scripts/protocol-and-json.js — не редактировать вручную.

export const PROTOCOL_VERSION = ${protocol.protocol};

export const ENUMS = {
${renderEnums(protocol.enums)}
} as const;

export const KEY = ENUMS.KEY;
export const CMD = ENUMS.CMD;
${Object.keys(protocol.enums)
  .filter((group) => group !== 'KEY' && group !== 'CMD')
  .map((group) => `export const ${group} = ENUMS.${group};`)
  .join('\n')}

export type TKey = keyof typeof KEY;
export type TCommand = typeof CMD[keyof typeof CMD];
export type TProtocol = typeof ENUMS;

export const STRUCTS = {
${renderStructs(protocol.structs)}
} as const;

${renderInterfaces(protocol.structs)}

${renderMessages(protocol)}
`;

const renderHeader = (protocol) => {
  const lines = [
    '// AUTO-GENERATED by scripts/protocol-and-json.js — не редактировать вручную.',
    '#pragma once',
    '',
    '#include <stddef.h>',
    '',
  ];

  for (const [name, struct] of Object.entries(protocol.structs)) {
    lines.push(`static_assert(sizeof(${name}) == ${struct.size}, "${name}: размер не совпадает с protocol.h");`);
    for (const field of struct.fields) {
      lines.push(`static_assert(offsetof(${name}, ${field.name}) == ${field.offset}, "${name}.${field.name}: смещение не совпадает");`);
    }
  }

  return lines.join('\n') + '\n';
};

const writeOrCheck = async (path, content) => {
  if (!check) {
    await fs.mkdir(normalize(join(path, '..')), { recursive: true });
    await fs.writeFile(path, content);
    return true;
  }

  const current = await fs.readFile(path, 'utf8').catch(() => null);
  if (current === content) return true;

  console.error(`[protocol] устарел: ${path}`);
  return false;
};

const run = async () => {
  const source = await fs.readFile(pathProtocol, 'utf8');
  const protocol = parseProtocol(source, { file: 'src/const/protocol.h' });
  const dataJson = await mergeJsonFiles(pathJson);

  const ts = renderTs(protocol);
  const header = renderHeader(protocol);
  const merged = { ...dataJson, struct: protocol };
  const staleProtocolPath = normalize(join(cwd, 'public/protocol.json'));

  const results = await Promise.all([
    writeOrCheck(pathDefaultJson, JSON.stringify(merged)),
    writeOrCheck(pathTs, ts),
    writeOrCheck(pathHeader, header),
  ]);

  // The separate protocol file is no longer produced; remove stale copies so a
  // local build cannot keep serving an outdated second JSON.
  if (check) {
    const stale = await fs.access(staleProtocolPath).then(() => true).catch(() => false);
    if (stale) {
      console.error(`[protocol] лишний файл: ${normalize(staleProtocolPath).replace(cwd, '.')}`);
      results.push(false);
    }
  } else {
    await fs.rm(staleProtocolPath, { force: true });
  }

  if (check && results.includes(false)) {
    process.exitCode = 1;
    return;
  }

  console.log(
    check
      ? '[protocol] всё актуально'
      : `[protocol] обновлено: ${[pathDefaultJson, pathTs, pathHeader].map((path) => normalize(path).replace(cwd, '.')).join(', ')}`,
  );
};

run().catch((error) => {
  console.error(error.message ?? error);
  process.exitCode = 1;
});
